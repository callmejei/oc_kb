from kb.config import REPO_ROOT, load_settings, read_dotenv

INFRA = REPO_ROOT / ".infra"
DATA = INFRA / "data"
LOGS = INFRA / "logs"
RUN = INFRA / "run"
DOWNLOADS = INFRA / "downloads"
DOTENV = REPO_ROOT / ".env.local"
IS_WIN = os.name == "nt"
EXE = ".exe" if IS_WIN else ""

