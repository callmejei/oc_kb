"""Local infrastructure: start / stop / health for PostgreSQL, Elasticsearch, Ollama and Phoenix.

No Docker. Official binaries live in .infra/ (fetched by `fetch`), data in .infra/data, logs in
.infra/logs, pids in .infra/run. Every process is started with a sanitized environment.

Usage:  uv run python infra/local/kbinfra.py {fetch|up|down|status|models} [service ...]
"""

