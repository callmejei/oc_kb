PG_BIN = INFRA / "pgsql" / "bin"
ES_HOME = INFRA / f"elasticsearch-{ES_VERSION}"
OLLAMA_BIN = INFRA / "ollama" / f"ollama{EXE}"


def log(msg: str) -> None:
    print(f"[kbinfra] {msg}", flush=True)


# ---- secrets ---------------------------------------------------------------------------------
SECRET_KEYS = ("KB_PG_ADMIN_PASSWORD", "KB_PG_API_PASSWORD", "KB_PG_PIPELINE_PASSWORD", "KB_ES_PASSWORD")


def ensure_secrets() -> dict[str, str]:
    env = read_dotenv(DOTENV)
    changed = False
    for k in SECRET_KEYS:
        if not env.get(k):
            env[k] = secrets.token_urlsafe(24)
            changed = True
    if changed:
        DOTENV.write_text(
            "# generated by kbinfra; local only, gitignored\n" + "".join(f"{k}={v}\n" for k, v in env.items()),
            encoding="utf-8",
        )
        log(f"wrote secrets to {DOTENV.name}")
    return env


# ---- process helpers -------------------------------------------------------------------------
def _flags() -> int:
    if not IS_WIN:
        return 0
    return subprocess.CREATE_NEW_PROCESS_GROUP | subprocess.CREATE_NO_WINDOW | 0x01000000  # BREAKAWAY_FROM_JOB


def spawn(name: str, cmd: list[str], extra_env: dict[str, str], cwd: Path | None = None) -> int:
    LOGS.mkdir(parents=True, exist_ok=True)
    RUN.mkdir(parents=True, exist_ok=True)
    out = open(LOGS / f"{name}.out.log", "ab")  # noqa: SIM115 - handle owned by the child
    kw: dict[str, Any] = {"stdout": out, "stderr": subprocess.STDOUT, "stdin": subprocess.DEVNULL, "cwd": cwd}
    try:
        p = (
            envsafe.popen(cmd, extra_env=extra_env, creationflags=_flags(), **kw)
            if IS_WIN
            else envsafe.popen(cmd, extra_env=extra_env, start_new_session=True, **kw)
        )
    except OSError:  # job does not allow breakaway
        p = envsafe.popen(
            cmd,
            extra_env=extra_env,
            creationflags=subprocess.CREATE_NEW_PROCESS_GROUP | subprocess.CREATE_NO_WINDOW,
            **kw,
        )
    (RUN / f"{name}.pid").write_text(str(p.pid))
    return p.pid


def kill_tree(name: str) -> None:
    pidf = RUN / f"{name}.pid"
    if not pidf.exists():
        return
    pid = pidf.read_text().strip()
    if IS_WIN:
        subprocess.run(["taskkill", "/PID", pid, "/T", "/F"], capture_output=True, check=False)  # noqa: S603,S607
    else:
        subprocess.run(["kill", "-TERM", f"-{pid}"], capture_output=True, check=False)  # noqa: S603,S607
    pidf.unlink(missing_ok=True)


def wait_for(name: str, check: Callable[[], bool], timeout: float) -> None:
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if check():
            return
        time.sleep(2)
    raise SystemExit(f"[kbinfra] {name} not healthy after {timeout:.0f}s; see .infra/logs/")


def http_ok(url: str, auth: tuple[str, str] | None = None, timeout: float = 3) -> tuple[bool, Any]:
    req = urllib.request.Request(url)  # noqa: S310 - loopback URLs from validated config
    if auth:
        req.add_header("Authorization", "Basic " + b64encode(f"{auth[0]}:{auth[1]}".encode()).decode())
    try:
        with urllib.request.urlopen(req, timeout=timeout) as r:  # noqa: S310
            body = r.read().decode("utf-8", "replace")
            try:
                return r.status == 200, json.loads(body)
            except ValueError:
                return r.status == 200, body
    except Exception:  # noqa: BLE001
        return False, None


def port_open(host: str, port: int) -> bool:
    with socket.socket() as sock:
        sock.settimeout(1)
        return sock.connect_ex((host, port)) == 0


# ---- fetch -----------------------------------------------------------------------------------
def _download(url: str, dest: Path) -> None:
    if dest.exists():
        return
    log(f"downloading {url}")
    tmp = dest.with_suffix(dest.suffix + ".part")
    with urllib.request.urlopen(url) as r, open(tmp, "wb") as f:  # noqa: S310 - pinned official URLs
        shutil.copyfileobj(r, f, 1 << 20)
    tmp.rename(dest)


def _hash(path: Path, algo: str) -> str:
    h = hashlib.new(algo)
    with open(path, "rb") as f:
        while b := f.read(1 << 20):
            h.update(b)
    return h.hexdigest()


def fetch() -> None:
    DOWNLOADS.mkdir(parents=True, exist_ok=True)
    for a in ARTIFACTS.values():
        zpath = DOWNLOADS / a["url"].rsplit("/", 1)[1]
        if (INFRA / f".extracted-{zpath.name}").exists():
            continue  # verified and extracted earlier
        _download(a["url"], zpath)
        if "sha512_url" in a:
            with urllib.request.urlopen(a["sha512_url"]) as r:  # noqa: S310
                expected = r.read().decode().split()[0]
            ok = _hash(zpath, "sha512") == expected
        elif "sha256_list" in a:
            with urllib.request.urlopen(a["sha256_list"]) as r:  # noqa: S310
                lines = r.read().decode().splitlines()
            expected = next(ln.split()[0] for ln in lines if ln.endswith(zpath.name))
            ok = _hash(zpath, "sha256") == expected
        else:
            ok = _hash(zpath, "sha256") == a["sha256"]
        if not ok:
            raise SystemExit(f"[kbinfra] checksum mismatch for {zpath.name}")
        log(f"{zpath.name}: checksum OK")
        marker = INFRA / f".extracted-{zpath.name}"
        if not marker.exists():
            with zipfile.ZipFile(zpath) as z:
                members = [m for m in z.namelist() if not m.startswith(("pgsql/pgAdmin 4/", "pgsql/StackBuilder/"))]
                z.extractall(INFRA / a["dest"], members)
            marker.touch()
            log(f"extracted {zpath.name}")


# ---- PostgreSQL ------------------------------------------------------------------------------
def _pg_env(settings: Any, env: dict[str, str]) -> dict[str, str]:
    return {
        "PGPASSWORD": env["KB_PG_ADMIN_PASSWORD"],
        "PGHOST": "127.0.0.1",
        "PGPORT": str(settings.services["postgres"]["port"]),
        "PGUSER": "kb_admin",
    }


def pg_psql(settings: Any, env: dict[str, str], sql: str, db: str = "postgres") -> str:
    r = envsafe.run(
        [str(PG_BIN / f"psql{EXE}"), "-X", "-At", "-v", "ON_ERROR_STOP=1", "-d", db, "-c", sql],
        extra_env=_pg_env(settings, env),
        capture_output=True,
        text=True,
    )
    return str(r.stdout).strip()


def pg_health(settings: Any, env: dict[str, str]) -> tuple[bool, str]:
    try:
        return True, pg_psql(settings, env, "select version()")
    except Exception as e:  # noqa: BLE001
        return False, str(e)


def pg_up(settings: Any, env: dict[str, str]) -> None:
    pgdata = DATA / "pg"
    port = settings.services["postgres"]["port"]
    if not (pgdata / "PG_VERSION").exists():
        pgdata.parent.mkdir(parents=True, exist_ok=True)
        pw = INFRA / "run" / "pgpw.tmp"
        pw.parent.mkdir(parents=True, exist_ok=True)
        pw.write_text(env["KB_PG_ADMIN_PASSWORD"], encoding="utf-8")
        try:
            envsafe.run(
                [
                    str(PG_BIN / f"initdb{EXE}"),
                    "-D",
                    str(pgdata),
                    "-U",
                    "kb_admin",
                    f"--pwfile={pw}",
                    "-A",
                    "scram-sha-256",
                    "-E",
                    "UTF8",
                    "--no-locale",
                ],
                capture_output=True,
            )
        finally:
            pw.unlink(missing_ok=True)
        log("initdb done")
    if pg_health(settings, env)[0]:
        log("postgres already running")
    else:
        # no capture_output: the postmaster inherits pipes and would block us forever
        envsafe.run(
            [
                str(PG_BIN / f"pg_ctl{EXE}"),
                "-D",
                str(pgdata),
                "-l",
                str(LOGS / "postgres.log"),
                "-w",
                "-o",
                f"-p {port} -c listen_addresses=127.0.0.1",
                "start",
            ],
            stdin=subprocess.DEVNULL,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
        wait_for("postgres", lambda: pg_health(settings, env)[0], 60)
    db = settings.services["postgres"]["database"]
    if not re.fullmatch(r"[a-z_][a-z0-9_]{0,62}", db):
        raise SystemExit(f"[kbinfra] invalid database name {db!r}")
    if pg_psql(settings, env, f"select 1 from pg_database where datname='{db}'") != "1":  # noqa: S608
        pg_psql(settings, env, f'create database "{db}"')
        log(f"created database {db}")
    log("postgres healthy")


def pg_down(settings: Any, env: dict[str, str]) -> None:
    pgdata = DATA / "pg"
    if (pgdata / "postmaster.pid").exists():
        envsafe.run(
            [str(PG_BIN / f"pg_ctl{EXE}"), "-D", str(pgdata), "-m", "fast", "-w", "stop"],
            capture_output=True,
            check=False,
        )
    log("postgres stopped")


# ---- Elasticsearch ---------------------------------------------------------------------------
ES_YML = """# managed by infra/local/kbinfra.py - LOCAL ONLY
cluster.name: kb-local
node.name: kb-1
path.data: {data}
path.logs: {logs}
network.host: 127.0.0.1
http.port: {http_port}
transport.port: {transport_port}
discovery.type: single-node
xpack.security.enabled: true
# LOCAL ONLY: plain HTTP on loopback; TLS is mandatory on CML
xpack.security.http.ssl.enabled: false
xpack.security.transport.ssl.enabled: false
xpack.security.enrollment.enabled: false
xpack.ml.enabled: false
ingest.geoip.downloader.enabled: false
action.destructive_requires_name: true
"""


def _es_url(settings: Any) -> str:
    return str(settings.services["elasticsearch"]["url"]).rstrip("/")


def es_health(settings: Any, env: dict[str, str]) -> tuple[bool, Any]:
    ok, body = http_ok(_es_url(settings) + "/_cluster/health", ("elastic", env["KB_ES_PASSWORD"]))
    return bool(ok and isinstance(body, dict) and body.get("status") in ("green", "yellow")), body


def es_up(settings: Any, env: dict[str, str]) -> None:
    if es_health(settings, env)[0]:
        log("elasticsearch already running")
        return
    port = int(_es_url(settings).rsplit(":", 1)[1])
    (DATA / "es").mkdir(parents=True, exist_ok=True)
    (LOGS / "es").mkdir(parents=True, exist_ok=True)
    (ES_HOME / "config" / "elasticsearch.yml").write_text(
        ES_YML.format(
            data=(DATA / "es").as_posix(), logs=(LOGS / "es").as_posix(), http_port=port, transport_port=port + 100
        ),
        encoding="utf-8",
    )
    heap = settings.services["elasticsearch"].get("heap", "2g")
    (ES_HOME / "config" / "jvm.options.d").mkdir(exist_ok=True)
    (ES_HOME / "config" / "jvm.options.d" / "heap.options").write_text(f"-Xms{heap}\n-Xmx{heap}\n")
    ks_tool = ES_HOME / "bin" / ("elasticsearch-keystore.bat" if IS_WIN else "elasticsearch-keystore")
    if not (ES_HOME / "config" / "elasticsearch.keystore").exists():
        # bootstrap.password is only read before the security index exists, i.e. on first start
        envsafe.run([str(ks_tool), "create"], capture_output=True)
        envsafe.run(
            [str(ks_tool), "add", "-x", "-f", "bootstrap.password"],
            input=env["KB_ES_PASSWORD"],
            text=True,
            capture_output=True,
        )
    es_bin = ES_HOME / "bin" / ("elasticsearch.bat" if IS_WIN else "elasticsearch")
    spawn("elasticsearch", [str(es_bin), "-p", str(RUN / "elasticsearch.java.pid")], {}, cwd=ES_HOME)
    wait_for("elasticsearch", lambda: es_health(settings, env)[0], 180)
    log("elasticsearch healthy")


def es_down(settings: Any, env: dict[str, str]) -> None:
    jpid = RUN / "elasticsearch.java.pid"
    if jpid.exists() and IS_WIN:
        subprocess.run(  # noqa: S603
            ["taskkill", "/PID", jpid.read_text().strip(), "/T", "/F"],  # noqa: S607
            capture_output=True,
            check=False,
        )
        jpid.unlink(missing_ok=True)
    kill_tree("elasticsearch")
    # taskkill returns before the JVM has released its files; wait until the port is closed
    port = int(_es_url(settings).rsplit(":", 1)[1])
    wait_for("elasticsearch shutdown", lambda: not port_open("127.0.0.1", port), 60)
    log("elasticsearch stopped")


# ---- Ollama ----------------------------------------------------------------------------------
def _ollama_env(settings: Any) -> dict[str, str]:
    url = str(settings.services["ollama"]["url"])
    return {
        "OLLAMA_HOST": url.split("://", 1)[1],
        "OLLAMA_MODELS": str((DATA / "ollama-models").resolve()),
        "OLLAMA_CONTEXT_LENGTH": "8192",  # default 2048 silently truncates RAG prompts
        "OLLAMA_KV_CACHE_TYPE": "q8_0",  # fit 8 GB VRAM
        "OLLAMA_FLASH_ATTENTION": "1",
        "OLLAMA_NOPRUNE": "1",
    }


def ollama_health(settings: Any, env: dict[str, str]) -> tuple[bool, Any]:
    return http_ok(str(settings.services["ollama"]["url"]) + "/api/version")


def ollama_up(settings: Any, env: dict[str, str]) -> None:
    if ollama_health(settings, env)[0]:
        log("ollama already running")
        return
    (DATA / "ollama-models").mkdir(parents=True, exist_ok=True)
    spawn("ollama", [str(OLLAMA_BIN), "serve"], _ollama_env(settings))
    wait_for("ollama", lambda: ollama_health(settings, env)[0], 60)
    log("ollama healthy")


def ollama_down(settings: Any, env: dict[str, str]) -> None:
    kill_tree("ollama")
    log("ollama stopped")


def ollama_models(settings: Any) -> None:
    model = settings.ports["llm"].options["model"]
    envsafe.run([str(OLLAMA_BIN), "pull", model], extra_env=_ollama_env(settings))
    log(f"model {model} present")


# ---- Phoenix ---------------------------------------------------------------------------------
def _phoenix_exe() -> Path:
    scripts = REPO_ROOT / ".venv" / ("Scripts" if IS_WIN else "bin")
    return scripts / f"phoenix{EXE}"


def phoenix_health(settings: Any, env: dict[str, str]) -> tuple[bool, Any]:
    return http_ok(str(settings.services["phoenix"]["url"]) + "/healthz")


def phoenix_up(settings: Any, env: dict[str, str]) -> None:
    if phoenix_health(settings, env)[0]:
        log("phoenix already running")
        return
    if not _phoenix_exe().exists():
        raise SystemExit("[kbinfra] phoenix not installed: run `uv sync --all-groups`")
    port = str(settings.services["phoenix"]["url"]).rsplit(":", 1)[1]
    (DATA / "phoenix").mkdir(parents=True, exist_ok=True)
    spawn(
        "phoenix",
        [str(_phoenix_exe()), "serve"],
        {
            "PHOENIX_HOST": "127.0.0.1",
            "PHOENIX_PORT": port,
            "PHOENIX_GRPC_PORT": "4317",
            "PHOENIX_WORKING_DIR": str(DATA / "phoenix"),
            "PHOENIX_TELEMETRY_ENABLED": "false",  # no outbound usage telemetry
            "PYTHONIOENCODING": "utf-8",
        },
    )
    wait_for("phoenix", lambda: phoenix_health(settings, env)[0], 120)
    log("phoenix healthy")


def phoenix_down(settings: Any, env: dict[str, str]) -> None:
    kill_tree("phoenix")
    log("phoenix stopped")


# ---- CLI -------------------------------------------------------------------------------------
SERVICES: dict[str, tuple[Callable[..., None], Callable[..., None], Callable[..., tuple[bool, Any]]]] = {
    "postgres": (pg_up, pg_down, pg_health),
    "elasticsearch": (es_up, es_down, es_health),
    "ollama": (ollama_up, ollama_down, ollama_health),
    "phoenix": (phoenix_up, phoenix_down, phoenix_health),
}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="kbinfra")
    ap.add_argument("action", choices=["fetch", "up", "down", "status", "models"])
    ap.add_argument("services", nargs="*", default=list(SERVICES))
    a = ap.parse_args(argv)
    if a.action == "fetch":
        fetch()
        return 0
    env = ensure_secrets()
    os.environ.update({k: v for k, v in env.items() if k.startswith("KB_")})
    settings = load_settings("local", strict=True)
    if a.action == "models":
        ollama_models(settings)
        return 0
    names = a.services
    if a.action == "up":
        fetch()
        for n in names:
            SERVICES[n][0](settings, env)
    elif a.action == "down":
        for n in reversed(names):
            SERVICES[n][1](settings, env)
    rc = 0
    if a.action in ("up", "status"):
        for n in names:
            ok, detail = SERVICES[n][2](settings, env)
            short = (
                detail.get("status")
                if isinstance(detail, dict) and "status" in detail
                else (json.dumps(detail) if isinstance(detail, dict) else str(detail))[:80]
            )
            print(f"  {n:<14} {'UP  ' if ok else 'DOWN'} {short}")
            rc |= 0 if ok else 1
    return rc


if __name__ == "__main__":
    sys.exit(main())
