"""Local authentication (Phase 3, D-028): username + password -> short-lived HS256 JWT.

- Passwords: one random password per synthetic user, generated by kbinfra; the gateway reads only
  salted scrypt hashes (.infra/secrets/local_users.hash.json). Local prototype only; CML uses SSO.
- Tokens carry identity only (sub). Groups are resolved from the IdentityProvider on every request,
  so a group change takes effect immediately, never cached in a token.
"""

from __future__ import annotations

import hashlib
import hmac
import json
import secrets
import time
import uuid
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import jwt

ISSUER = "kb-local-gateway"
AUDIENCE = "kb-gateway"
ALGORITHM = "HS256"
SCRYPT = {"n": 2**14, "r": 8, "p": 1, "dklen": 32}


class AuthError(Exception):
    pass


def hash_password(password: str, salt: bytes | None = None) -> str:
    salt = salt or secrets.token_bytes(16)
    dk = hashlib.scrypt(password.encode(), salt=salt, **SCRYPT)
    return f"scrypt${salt.hex()}${dk.hex()}"


def verify_password(password: str, stored: str) -> bool:
    try:
        scheme, salt_hex, dk_hex = stored.split("$")
    except ValueError:
        return False
    if scheme != "scrypt":
        return False
    dk = hashlib.scrypt(password.encode(), salt=bytes.fromhex(salt_hex), **SCRYPT)
    return hmac.compare_digest(dk.hex(), dk_hex)


def generate_local_users(user_ids: list[str], secrets_dir: Path) -> dict[str, str]:
    """Create (once) a random password per user: plaintext list for the operator, hashes for the gateway."""
    secrets_dir.mkdir(parents=True, exist_ok=True)
    hashes_path = secrets_dir / "local_users.hash.json"
    plain_path = secrets_dir / "local_users.txt"
    hashes: dict[str, str] = json.loads(hashes_path.read_text(encoding="utf-8")) if hashes_path.exists() else {}
    new: dict[str, str] = {}
    for uid in user_ids:
        if uid not in hashes:
            pw = secrets.token_urlsafe(12)
            hashes[uid] = hash_password(pw)
            new[uid] = pw
    if new:
        hashes_path.write_text(json.dumps(hashes, indent=1, sort_keys=True), encoding="utf-8")
        with open(plain_path, "a", encoding="utf-8") as f:
            for uid, pw in new.items():
                f.write(f"{uid}\t{pw}\n")
    return new


@dataclass(frozen=True)
class TokenIssuer:
    secret: str
    ttl_minutes: int = 60

    def __post_init__(self) -> None:
        if len(self.secret) < 32:
            raise ValueError("JWT secret must be at least 32 characters")

    def issue(self, user_id: str) -> dict[str, Any]:
        now = int(time.time())
        exp = now + self.ttl_minutes * 60
        token = jwt.encode(
            {
                "sub": user_id,
                "iat": now,
                "nbf": now,
                "exp": exp,
                "iss": ISSUER,
                "aud": AUDIENCE,
                "jti": uuid.uuid4().hex,
            },
            self.secret,
            algorithm=ALGORITHM,
        )
        return {"access_token": token, "token_type": "bearer", "expires_in": exp - now}

    def verify(self, token: str) -> str:
        try:
            claims = jwt.decode(
                token,
                self.secret,
                algorithms=[ALGORITHM],
                audience=AUDIENCE,
                issuer=ISSUER,
                options={"require": ["sub", "exp", "iat", "iss", "aud"]},
            )
        except jwt.PyJWTError as e:
            raise AuthError(str(e)) from None
        return str(claims["sub"])


class LocalPasswordStore:
    def __init__(self, hashes_path: Path) -> None:
        self.path = hashes_path

    def check(self, user_id: str, password: str) -> bool:
        if not self.path.exists():
            return False
        hashes: dict[str, str] = json.loads(self.path.read_text(encoding="utf-8"))
        stored = hashes.get(user_id)
        if stored is None:
            verify_password(password, hash_password("timing-equaliser"))  # same work for unknown users
            return False
        return verify_password(password, stored)
