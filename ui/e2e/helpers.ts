import { expect, type Browser, type Page } from "@playwright/test";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));

export interface Run {
  run: string;
  source_id: string;
  site: string;
  folder: string;
  policy_title: string;
  policy_question: string;
  policy_answer: string;
  upload_path: string;
  upload_title: string;
  upload_question: string;
  upload_answer: string;
}

export const run: Run = JSON.parse(readFileSync(join(HERE, ".run.json"), "utf-8"));
export const REPO = join(HERE, "..", "..");

// local login passwords generated by `kb.ps1 up` (synthetic users only)
export const PASSWORDS: Record<string, string> = Object.fromEntries(
  readFileSync(join(HERE, "..", "..", ".infra", "secrets", "local_users.txt"), "utf-8")
    .split(/\r?\n/)
    .filter(Boolean)
    .map((l) => l.trim().split(/\s+/) as [string, string]),
);

/** A fresh browser context per user (the token lives in sessionStorage), signed in through the form. */
export async function as(browser: Browser, user: string): Promise<Page> {
  const ctx = await browser.newContext();
  const page = await ctx.newPage();
  page.on("dialog", (d) => d.accept()); // confirm() dialogs
  await page.goto("/login");
  await page.fill("input[name=username]", user);
  await page.fill("input[name=password]", PASSWORDS[user]);
  await page.click("button[type=submit]");
  await expect(page.getByTestId("who")).toContainText(user);
  return page;
}

/** Ask in the chat and return the newest answer card. */
export async function ask(page: Page, question: string) {
  if (!page.url().endsWith("/chat")) await page.click("nav >> text=Ask");
  const before = await page.getByTestId("answer").count();
  await page.fill("textarea[name=question]", question);
  await page.click("form.ask button[type=submit]");
  await expect(page.getByTestId("answer")).toHaveCount(before + 1, { timeout: 180_000 });
  return page.getByTestId("answer").last();
}

/** Ask until the answer contains `text` (the pipeline is asynchronous: sensors, parse, index). */
export async function askUntil(page: Page, question: string, text: string, timeoutMs: number) {
  const until = Date.now() + timeoutMs;
  for (;;) {
    const a = await ask(page, question);
    if ((await a.innerText()).includes(text)) return a;
    if (Date.now() > until) throw new Error(`answer never contained ${text}: ${await a.innerText()}`);
    await page.waitForTimeout(15_000);
  }
}
